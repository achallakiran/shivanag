import { NullEngine } from '@babylonjs/core/Engines/nullEngine';
import { Vector3 } from '@babylonjs/core/Maths/math.vector';
import { writeFileSync, mkdirSync } from 'node:fs';
import { CreateSphere } from '@babylonjs/core/Meshes/Builders/sphereBuilder';
import { StandardMaterial } from '@babylonjs/core/Materials/standardMaterial';
import { Color3 } from '@babylonjs/core/Maths/math.color';
import { createStage, frame } from '../src/voxel/stage';
import { createBatsman } from '../src/voxel/rig';
import { STANCES } from '../src/voxel/poses';
import { CAMS } from '../src/game/cameras';
import { rasterize, png } from './raster';
const out = process.argv[2]!; mkdirSync(out, { recursive: true });
const stage = createStage(new NullEngine());
createBatsman(stage.scene, stage.voxelMat).apply(STANCES[0]!.pose);
const m = new StandardMaterial('b', stage.scene); m.disableLighting = true; m.emissiveColor = new Color3(0.9, 0.1, 0.1); m.diffuseColor = new Color3(0, 0, 0);
const b = CreateSphere('b', { diameter: 0.24, segments: 8 }, stage.scene); b.material = m;
const ballZ = Number(process.env.BALLZ ?? 9);
b.position.set(0.1, 1.2, ballZ);
CAMS.forEach((c, i) => {
  b.scaling.setAll(c.ball);
  if (c.fov) { stage.cam.position.set(...c.pos); stage.cam.setTarget(new Vector3(...c.target)); stage.cam.fov = (c.fov * Math.PI) / 180; } else frame(stage.cam, c.pos, c.target, c.fill);
  writeFileSync(`${out}/c${i}.png`, png(rasterize(stage.scene, 640, 360), 640, 360));
});
